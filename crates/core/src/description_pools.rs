//! What generated profile descriptions are made of. Every template holds options in
//! `{a|b|c}`, nested ones too, and `{country}`; an empty option leaves a part out.
//! Nothing here uses square brackets, which Steam reads as formatting.

use crate::descriptions::Piece;

/// The words for one language.
pub struct Words {
    greetings: &'static [&'static str],
    about: &'static [&'static str],
    games: &'static [&'static str],
    status: &'static [&'static str],
    trade_notes: &'static [&'static str],
    /// Sayings, without quote marks: those are picked separately.
    pub quotes: &'static [&'static str],
    /// Who a quote is from, when it says.
    pub quote_by: &'static str,
    /// As they read after "from", in Russian after "из".
    pub countries: &'static [&'static str],
}

impl Words {
    /// The templates for a piece made of words.
    pub fn pool(&self, piece: Piece) -> &'static [&'static str] {
        match piece {
            Piece::Greeting => self.greetings,
            Piece::About => self.about,
            Piece::Games => self.games,
            Piece::Status => self.status,
            Piece::TradeNote => self.trade_notes,
            Piece::Quote | Piece::Ascii | Piece::Kaomoji | Piece::Divider => &[],
        }
    }
}

pub fn english() -> &'static Words {
    &ENGLISH
}

pub fn russian() -> &'static Words {
    &RUSSIAN
}

